/**
 * Returns a personalized list of kid-friendly board game news articles based on:
 * 1. Games discussed in companion chat history
 * 2. Active board game selected on the table
 * 3. General family-friendly rotation when no history exists
 */
export function getPersonalizedNews(chatHistory = [], activeGame = "Catan") {
  const discussedCounts = new Map();

  if (activeGame) {
    discussedCounts.set(activeGame.toLowerCase(), 15);
  }

  // Scan chat history for game keywords
  if (Array.isArray(chatHistory)) {
    chatHistory.forEach((msg) => {
      const text = (msg.text || "").toLowerCase();
      boardGameNews.forEach((item) => {
        const gameLower = item.game.toLowerCase();
        if (text.includes(gameLower)) {
          discussedCounts.set(gameLower, (discussedCounts.get(gameLower) || 0) + 5);
        }
      });
    });
  }

  // Score articles
  const scored = boardGameNews.map((article) => {
    const gameLower = article.game.toLowerCase();
    const chatBoost = discussedCounts.get(gameLower) || 0;
    // Add small deterministic jitter for fresh rotations
    const randomBoost = Math.sin(article.id.length * 17) * 2;
    return {
      ...article,
      score: chatBoost + randomBoost,
    };
  });

  // Sort descending by personalization score
  return scored.sort((a, b) => b.score - a.score);
}
